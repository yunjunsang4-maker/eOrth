export interface RegionCities { ko: string[]; en: string[] }

/** 지역 코드의 주요 도시. 없으면 null — 호출부는 괄호를 붙이지 않는다. */
export function regionMajorCities(code: string | null | undefined): RegionCities | null {
  const raw = code ? REGION_MAJOR_CITIES[code] : undefined;
  if (!raw) return null;
  const [ko, en] = raw.split('|');
  return { ko: ko.split('·'), en: (en || ko).split('·') };
}

/**
 * 검색어가 이 지역의 주요 도시(한글·영문) 중 하나에 들어맞는가 — '경주' → 경상북도, 'yokohama' → 가나가와현.
 * 대소문자 무시·앞뒤 공백 무시. 빈 검색어는 false(필터 쪽에서 빈 검색어는 전체 노출로 따로 처리한다).
 */
export function regionCitiesMatch(code: string | null | undefined, query: string): boolean {
  const q = query.trim().toLowerCase();
  const c = q ? regionMajorCities(code) : null;
  if (!c) return false;
  return c.ko.some(s => s.includes(q)) || c.en.some(s => s.toLowerCase().includes(q));
}
